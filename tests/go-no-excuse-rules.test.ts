import { expect, test } from "bun:test";
import { mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";

const checker = resolve(import.meta.dir, "../skills/programming/scripts/go/check-no-excuse-rules.sh");

function audit(files: Readonly<Record<string, string>>) {
  const cwd = mkdtempSync(join(tmpdir(), "go-no-excuse-"));
  try {
    for (const [file, text] of Object.entries(files)) writeFileSync(join(cwd, file), text);
    const result = Bun.spawnSync(["bash", checker, ...Object.keys(files)], { cwd });
    const diagnostics = Array.from(
      result.stderr.toString().matchAll(/^::(error|warning) file=([^,]+),line=\d+::\[([\w-]+)\](?: (\d+) pure LOC)?/gm),
      ([, severity, file, rule, loc]) => ({ severity, file, rule, loc }),
    ).sort((left, right) => left.rule.localeCompare(right.rule));
    return { status: result.exitCode, diagnostics };
  } finally {
    rmSync(cwd, { recursive: true, force: true });
  }
}

const license = Array.from({ length: 7 }, (_, i) => `// License notice line ${i + 1}\n`).join("");
const packageBody = `import ("context"; "fmt"; "log")
func main() {
	_ = context.Background()
	fmt.Println("output")
	log.Fatal("exit")
	panic("exit")
}
`;

test("only library source triggers package rules after a license and package-like comment", () => {
  const header = `${license}/*\npackage main\n*/\n`;
  const files = {
    "command with spaces.go": `${header}package /* command */ main // CLI\n${packageBody}`,
    "worker.go": `${header}package worker\n${packageBody}`,
    "worker_test.go": `${header}package worker_test\n${packageBody}`,
  };

  expect(audit(files)).toEqual({
    status: 1,
    diagnostics: ["ctx-background-in-lib", "fmt-print-in-lib", "log-fatal-in-lib", "panic-in-lib"]
      .map((rule) => ({ severity: "error", file: "worker.go", rule, loc: undefined })),
  });
});

const atCeiling = [
  "package fixture",
  "/*",
  "Package note",
  "*/var data = `",
  "// allow: SIZE_OK — literal data, not an exception",
  "/* still literal data */",
  "",
  "`",
  ...Array.from({ length: 245 }, (_, i) => `const n${i} = ${i} // count this line once`),
  "",
].join("\n");
const overCeiling = `${atCeiling}//line virtual.go:1\nconst extra = 1\n`;

test.each([
  ["warns at 250", {
    source: atCeiling, status: 0, severity: "warning", rule: "size-warning", loc: "250",
  }],
  ["fails at 251 without a real justification", {
    source: `${overCeiling}// allow: SIZE_OK —\n`, status: 1, severity: "error", rule: "oversized-file", loc: "251",
  }],
  ["warns at 251 with a justified exception", {
    source: `${overCeiling}// allow: SIZE_OK — Keep this indivisible table together.\n`, status: 0, severity: "warning", rule: "oversized-file", loc: "251",
  }],
] as const)("Go checker %s", (_description, { source, status, severity, rule, loc }) => {
  expect(audit({ "data.go": source })).toEqual({
    status,
    diagnostics: [{ severity, file: "data.go", rule, loc }],
  });
});

test("generated suffix and header exclusions skip otherwise failing Go files", () => {
  const files = {
    "schema.pb.go": "package fixture\nfunc init() {}\n",
    "data.go": `${license}// Code generated by fixture generator. DO NOT EDIT.\n${overCeiling}`,
  };

  expect(audit(files)).toEqual({ status: 0, diagnostics: [] });
});
